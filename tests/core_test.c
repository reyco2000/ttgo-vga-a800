#include "6502.h"
#include "Antic.h"
#include "Atari.h"
#include "AtariIo.h"
#include "Gtia.h"
#include "Pia.h"
#include "Pokey.h"
#include <assert.h>
#include <string.h>

int main(void) {
  Atari a;
  memset(&a, 0, sizeof(a));
  a.s = 0xfd;
  a.p = 0x24;
  const uint8_t program[] = {0xa9, 0x10, 0x69, 0x22, 0x85, 0x80,
                             0xa2, 3,    0xca, 0xd0, 0xfd};
  memcpy(a.ram + 0x200, program, sizeof(program));
  a.pc = 0x200;
  for (int i = 0; i < 11; i++)
    Cpu_Step(&a);
  assert(a.ram[0x80] == 0x32);
  assert(a.x == 0);
  a.pc = 0x400;
  a.x = 1;
  a.ram[0x400] = 0xbd;
  a.ram[0x401] = 0xff;
  a.ram[0x402] = 0;
  a.ram[0x100] = 0x55;
  assert(Cpu_Step(&a) == 5);
  assert(a.a == 0x55);
  a.pc = 0x4fd;
  a.p = 0x20;
  a.ram[0x4fd] = 0xd0;
  a.ram[0x4fe] = 2;
  assert(Cpu_Step(&a) == 4);
  assert(a.pc == 0x501);
  a.pia[1] = 1;
  a.pia_ddr[1] = 1;
  a.os[0x3ffc] = 0x34;
  a.os[0x3ffd] = 0x12;
  Cpu_Reset(&a);
  assert(a.pc == 0x1234);
  assert(Gtia_Color(0) == 0xff0c0c0cu);
  Atari_SetVideoStandard(&a, A800_NTSC);
  assert(a.frame_lines == 262);
  assert(a.cpu_hz == 1789772u);
  assert(Gtia_Read(&a, 0xd014) == 0x0f);
  Atari_SetVideoStandard(&a, A800_PAL);
  assert(a.frame_lines == 312);
  assert(a.cpu_hz == 1773447u);
  assert(Gtia_Read(&a, 0xd014) == 0x01);
  memset(a.trigger, 1, sizeof(a.trigger));
  memset(a.trigger_latch, 1, sizeof(a.trigger_latch));
  Gtia_Write(&a, 0xd01d, 4);
  a.trigger[0] = 0;
  Gtia_Frame(&a);
  a.trigger[0] = 1;
  assert(Gtia_Read(&a, 0xd010) == 0);
  Gtia_Write(&a, 0xd01d, 0);
  assert(Gtia_Read(&a, 0xd010) == 1);
  Pia_Reset(&a);
  Pia_Write(&a, 0xd301, 0xff);
  assert(a.pia_ddr[1] == 0xff);
  assert(Atari_PortB(&a) == 0xff);
  Pia_Write(&a, 0xd303, 4);
  Pia_Write(&a, 0xd301, 0xfd);
  assert(Atari_PortB(&a) == 0xfd);
  a.pokey_irqst = 0xff;
  a.pokey_irqen = 0;
  Pokey_Write(&a, 0xd20e, 0x40);
  assert(a.pokey_irqen == 0x40);
  assert(Pokey_Read(&a, 0xd20e) == 0xff);
  a.pokey_skstat = 0xff;
  Pokey_Write(&a, 0xd20f, 3);
  assert(a.pokey_skctl == 3);
  assert(Pokey_Read(&a, 0xd20f) == 0xff);
  a.cpu_hz = 1789772;
  a.pokey[0] = 10;
  a.pokey[1] = 0xaf;
  int16_t audio[512];
  Pokey_Audio(&a, audio, 512, 44100);
  int changes = 0;
  for (int i = 1; i < 512; i++)
    changes += audio[i] != audio[i - 1];
  assert(changes > 10);
  a.pokey[0] = 0;
  a.pokey[1] = 0xa8;
  int16_t ultrasonic[4096];
  Pokey_Audio(&a, ultrasonic, 4096, 44100);
  assert(ultrasonic[4095] < 100 && ultrasonic[4095] > -100);
  a.audio_phase[0] = .5;
  a.audio_output[0] = 1;
  Pokey_Write(&a, 0xd209, 0);
  assert(a.audio_phase[0] == 0 && a.audio_output[0] == 0);
  a.pokey_irqst = 0xff;
  a.pokey_irqen = 1;
  a.pokey[0] = 0;
  a.pokey[8] = 0x40;
  a.cycles = 4;
  a.pokey_timer_base = 0;
  Pokey_Advance(&a, 4);
  assert(!(a.pokey_irqst & 1));
  a.pokey_irqst = 0xff;
  a.pokey_irqen = 2;
  a.pokey[0] = a.pokey[2] = 0;
  a.pokey[8] = 0x50;
  a.cycles = 7;
  a.pokey_timer_base = 0;
  Pokey_Advance(&a, 7);
  assert(!(a.pokey_irqst & 2));
  a.pc = 0xe474;
  a.option_override = 1;
  a.ram[0x0c] = 0x34;
  a.ram[0x0d] = 0x12;
  assert(Cpu_Step(&a) == 3);
  assert(a.pc == 0x1234);
  memset(a.ram + 0x300, 0, 12);
  a.ram[0x300] = 0x31;
  a.ram[0x301] = 1;
  a.ram[0x302] = 0x52;
  assert(AtariIo_Sio(&a) == 0x8a);
  memset(&a, 0, sizeof(a));
  Atari_SetVideoStandard(&a, A800_NTSC);
  a.pia[1] = 0;
  a.pia_ddr[1] = 0xff;
  a.antic[0] = 2;
  a.antic[2] = 0x00;
  a.antic[3] = 0x02;
  a.antic[9] = 0xe0;
  a.line_antic[8][9] = 0xe0;
  a.gtia[23] = 0x4a;
  a.line_colors[8][1] = 0x4a;
  a.ram[0x200] = 0x47;
  a.ram[0x201] = 0x00;
  a.ram[0x202] = 0x03;
  a.ram[0x203] = 0x41;
  a.ram[0x204] = 0x00;
  a.ram[0x205] = 0x02;
  a.ram[0x300] = 0x40;
  a.ram[0xe000] = 0x80;
  a.antic[9] = 0;
  Antic_Frame(&a);
  assert(a.pixels[8 * A800_WIDTH + 32] == Gtia_Color(0x4a));
  a.ram[0x200] = 0x57;
  a.line_antic[8][4] = 2;
  Antic_Frame(&a);
  assert(a.pixels[8 * A800_WIDTH + 32] == Gtia_Color(0));
  assert(a.pixels[8 * A800_WIDTH + 36] == Gtia_Color(0x4a));
  a.ram[0x200] = 0x66;
  a.line_antic[8][4] = 0;
  a.line_antic[8][5] = 1;
  a.ram[0x300] = 0;
  a.ram[0xe001] = 0;
  Antic_Frame(&a);
  assert(a.pixels[8 * A800_WIDTH + 32] == Gtia_Color(0));
  a.ram[0x200] = 0x42;
  a.line_antic[8][1] = 1;
  a.line_antic[8][5] = 0;
  a.ram[0x300] = 0x80;
  Antic_Frame(&a);
  assert(a.pixels[8 * A800_WIDTH + 32] == Gtia_Color(0));
  a.line_antic[8][1] = 3;
  Antic_Frame(&a);
  assert(a.pixels[8 * A800_WIDTH + 32] == Gtia_Color(0x0a));
  memset(a.ram, 0, sizeof(a.ram));
  a.antic[2] = 0;
  a.antic[3] = 2;
  a.ram[0x200] = 0xf0;
  a.ram[0x201] = 0x41;
  a.ram[0x202] = 0;
  a.ram[0x203] = 2;
  Antic_ScheduleDlis(&a);
  assert(a.dli_lines[15]);
  memset(&a, 0, sizeof(a));
  Atari_SetVideoStandard(&a, A800_NTSC);
  a.pia[1] = 0;
  a.pia_ddr[1] = 0xff;
  a.antic[0] = 0x1a;
  a.antic[7] = 0x30;
  a.line_gtia[40][0] = 0x80;
  a.line_gtia[40][18] = 0x4a;
  a.line_gtia[40][29] = 2;
  a.scanline = 40;
  a.ram[0x3428] = 0x80;
  Antic_CaptureLine(&a);
  a.ram[0x3428] = 0;
  Antic_Frame(&a);
  assert(a.pixels[40 * A800_WIDTH + 192] == Gtia_Color(0x4a));
  a.gtia[28] = 1;
  a.pm_latch[0] = 0x40;
  a.ram[0x3428] = 0x80;
  a.scanline = 40;
  Antic_CaptureLine(&a);
  assert(a.line_pmg[40][0] == 0x40);
  a.ram[0x3429] = 0x80;
  a.scanline = 41;
  Antic_CaptureLine(&a);
  assert(a.line_pmg[41][0] == 0x80);
  memset(&a, 0, sizeof(a));
  Atari_SetVideoStandard(&a, A800_NTSC);
  a.pia[1] = 0;
  a.pia_ddr[1] = 0xff;
  a.antic[0] = 0x1e;
  a.antic[2] = 0;
  a.antic[3] = 2;
  a.antic[7] = 0x30;
  a.ram[0x200] = 0x49;
  a.ram[0x201] = 0;
  a.ram[0x202] = 3;
  a.ram[0x203] = 0x41;
  a.ram[0x204] = 0;
  a.ram[0x205] = 2;
  a.ram[0x300] = 0x80;
  for (int line = 8; line < 12; line++)
    a.line_colors[line][0] = 0x4a;
  a.line_gtia[8][0] = a.line_gtia[8][1] = a.line_gtia[8][4] = 48;
  a.line_gtia[8][18] = 0x2a;
  a.line_gtia[8][19] = 0x4a;
  a.line_gtia[8][29] = 3;
  a.line_pmg[8][4] = 2;
  a.line_pmg[8][0] = a.line_pmg[8][1] = 0x80;
  Antic_Frame(&a);
  assert(a.pixels[8 * A800_WIDTH + 32] == Gtia_Color(0x6a));
  assert(a.pixels[8 * A800_WIDTH + 33] == Gtia_Color(0x6a));
  assert(a.pixels[8 * A800_WIDTH + 34] == Gtia_Color(0x4a));
  a.line_gtia[8][27] = 1;
  Antic_Frame(&a);
  assert(a.pixels[8 * A800_WIDTH + 32] == Gtia_Color(0x2a));
  a.line_gtia[8][27] = 4;
  Antic_Frame(&a);
  assert(a.pixels[8 * A800_WIDTH + 32] == Gtia_Color(0x4a));
  assert((Gtia_Read(&a, 0xd000) & 1) != 0);
  assert((Gtia_Read(&a, 0xd004) & 1) != 0);
  assert((Gtia_Read(&a, 0xd008) & 3) == 3);
  assert((Gtia_Read(&a, 0xd00c) & 2) != 0);
  assert((Gtia_Read(&a, 0xd00d) & 1) != 0);
  Gtia_Write(&a, 0xd01e, 0);
  for (int i = 0; i < 16; i++)
    assert(a.gtia_collisions[i] == 0);
  memset(&a, 0, sizeof(a));
  Atari_SetVideoStandard(&a, A800_NTSC);
  a.pia[1] = 0;
  a.pia_ddr[1] = 0xff;
  a.antic[0] = 2;
  a.antic[2] = 0;
  a.antic[3] = 2;
  a.ram[0x200] = 0x4f;
  a.ram[0x201] = 0;
  a.ram[0x202] = 3;
  a.ram[0x203] = 0x41;
  a.ram[0x204] = 0;
  a.ram[0x205] = 2;
  a.ram[0x300] = 0x1f;
  a.line_colors[8][4] = 0x40;
  a.line_gtia[8][27] = 0x40;
  Antic_Frame(&a);
  assert(a.pixels[8 * A800_WIDTH + 32] == Gtia_Color(0x41));
  assert(a.pixels[8 * A800_WIDTH + 36] == Gtia_Color(0x4f));
  a.ram[0x300] = 0x07;
  a.line_gtia[8][27] = 0x80;
  a.line_gtia[8][18] = 0x2a;
  a.line_colors[8][3] = 0x8a;
  Antic_Frame(&a);
  assert(a.pixels[8 * A800_WIDTH + 32] == Gtia_Color(0x2a));
  assert(a.pixels[8 * A800_WIDTH + 36] == Gtia_Color(0x8a));
  a.ram[0x300] = 0x1f;
  a.line_gtia[8][27] = 0xc0;
  a.line_colors[8][4] = 0x06;
  Antic_Frame(&a);
  assert(a.pixels[8 * A800_WIDTH + 32] == Gtia_Color(0x16));
  assert(a.pixels[8 * A800_WIDTH + 36] == Gtia_Color(0xf6));
  a.console = 7;
  a.option_override = 2;
  assert(Gtia_Read(&a, 0xd01f) == 3);
  assert(Gtia_Read(&a, 0xd01f) == 3);
  assert(Gtia_Read(&a, 0xd01f) == 7);
  memset(&a, 0, sizeof(a));
  Atari_SetVideoStandard(&a, A800_NTSC);
  a.line_gtia[40][0] = 0x80;
  a.line_gtia[40][13] = 0x80;
  a.line_gtia[40][18] = 0x2a;
  a.line_gtia[40][29] = 2;
  a.line_pmg[40][0] = 0x80;
  Antic_Frame(&a);
  assert(a.pixels[40 * A800_WIDTH + 192] == Gtia_Color(0x2a));
  return 0;
}
